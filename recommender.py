def validate(data):
    if not isinstance(data, dict):
        raise ValueError("Ожидался объект с параметрами бизнеса")
    for key, choices in (("activity", ACTIVITIES), ("scale", SCALES), ("investment", INVESTMENTS), ("risk", RISKS)):
        if not isinstance(data.get(key), str) or data[key] not in choices:
            raise ValueError(f"Выберите корректное значение: {key}")
    count = data.get("founders")
    if type(count) is not int or not 1 <= count <= 10000:
        raise ValueError("Количество учредителей должно быть целым числом от 1 до 10 000")


